    async def _sql_correction_agent(self, state: SubGraph_State) -> SubGraph_State:
        """
        Supervisor node: placeholder that ensures the suprivisor_response
        field exists on the SubGraph_State and sets it to None for now.
        """
        await sql_correction(state,
                        self.llm,
                        self.prompts.sql_correction_prompt,
                        self.logger
                        )
        # self.logger.info(f"Context builder response: {state.context_builder_response}")
        return state
    
    async def _execute_query(self, state: SubGraph_State) -> SubGraph_State:
        """
        Execute the SQL query generated by the Text2SQL generator and update the state.
        """
        await execute_query(
            state,
            self.db_conn,
            self.logger
        )
        return state
    
    def _sql_generation_router(self, state: SubGraph_State) -> list[str]:
        routes = []

        if state.fallback_response:
            routes.append("fallback")
        else:
            routes.append("sql_execution")

        return routes

    def _sql_execution_router(self, state: SubGraph_State) -> list[str]:
        routes = []

        if state.fallback_response and state.fallback_response.fallback_reason != "query_error":
            routes.append("fallback")
        elif state.fallback_response and state.fallback_response.fallback_reason == "query_error" and not state.sql_query_correction:
            routes.append("sql_correction")
        else:
            routes.append("end")

        return routes
    
    def _sql_query_correction(self, state: SubGraph_State) -> list[str]:
        routes = []

        if state.fallback_response:
            routes.append("fallback")
        else:
            routes.append("sql_execution")

        return routes


    
    async def _fallback(self, state: SubGraph_State):
        """
        Fallback node: placeholder that ensures the fallback_response
        field exists on the SubGraph_State and sets it to None for now.
        """
        await fallback_agent(state,
                              self.logger
        )
        self.logger.info(f"Fallback response: {state.fallback_response}")
        return {
            "fallback_response": state.fallback_response
        }
