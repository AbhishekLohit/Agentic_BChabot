class Agent_SubGraph:
    def __init__(self, 
                 openai_llm:LLMType,
                 prompts:Prompts,
                 logger: Logger,
                 db_conn: Any
                 ):
        self.llm = openai_llm
        self.prompts = prompts
        self.app = self._workflow()
        self.logger = logger
        self.db_conn = db_conn

    def _workflow(self):
        builder = StateGraph(SubGraph_State)

        ## DEFINE NODES ##
        builder.add_node("sql_generation", self._text2sql_generator)
        builder.add_node("sql_correction", self._sql_correction_agent)
        builder.add_node("sql_execution", self._execute_query)
        builder.add_node("fallback", self._fallback)
        
        
        ## DEFINE FLOW ##
        builder.add_edge(START, "sql_generation")
        builder.add_conditional_edges(
            "sql_generation",
            self._sql_generation_router,
            {
                "sql_execution": "sql_execution",
                "fallback": "fallback",
            }
        )
        builder.add_conditional_edges(
            "sql_execution",
            self._sql_execution_router,
            {
                "sql_correction": "sql_correction",
                "fallback": "fallback",
                "end": END
            }
        )
        builder.add_conditional_edges(
            "sql_correction",
            self._sql_query_correction,
            {
                "sql_execution": "sql_execution",
                "fallback": "fallback",
            }
        )
        builder.add_edge("fallback", END)
        app = builder.compile()
        return app

   
